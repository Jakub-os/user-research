 await p.evaluate(()=>document.querySelector('#amount-value').scrollIntoView({block:'center'}));
 const q=p.locator('#amount-value');
 await q.click({clickCount:3}); await p.keyboard.press('Delete');
 if(v) await p.keyboard.type(v);
